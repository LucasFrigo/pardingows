// Named event times for the gags, derived from the sung words in timeline.json, so Blender (shots.py) and the HUD (hud.mjs)
// fire every gag at the same moment and a sync fix moves both. Re-run after editing word times:
//   node src/pardao/make_cues.mjs        -> src/pardao/cues.json
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const TL = JSON.parse(fs.readFileSync(path.join(HERE, 'timeline.json'), 'utf8'));
const BEAT = 60 / TL.bpm;
const w = (line, i, off = 0) => +(TL.lines[line - 1].words[i][1] + off).toFixed(3);
const cut = n => TL.shots[n - 1].t;

const C = {
  descobri: w(1, 0), pardo1: w(1, 4),
  escuro: w(2, 4),
  p2_land: w(3, 0), p3_land: w(3, 1, 0.32), p4_land: w(3, 3),
  grab: w(4, 1), turn: w(4, 3), jab: w(4, 4), recoil: w(4, 5),
  radio_land: w(5, 0, 0.2),
  absurdo: w(6, 3),
  enquadram: w(7, 3, -0.03),
  fire0: w(8, 1), fire1: w(8, 1, 0.23), fire2: w(8, 2), fire3: w(8, 3), fire4: w(8, 3, 0.13),
  gameover: w(8, 3, 0.23), lamento: w(8, 4),
  cont9: w(9, 0), cont8: w(9, 1), press: w(9, 2),
  dance: w(10, 2),
  terca: w(11, 4), cola: w(11, 3),
  lista: w(12, 2),
  ideias: w(13, 2),
  qte: w(14, 0), qte_press: w(14, 0, 0.48), impact: w(14, 2),
  sotaque: w(15, 2),
  boss: cut(16), charge: +(cut(16) + 0.27).toFixed(3), sidestep: w(16, 2), crash: w(16, 3),
  tag: w(17, 0),
};
const out = { _: 'Generated by make_cues.mjs from timeline.json word times. Song seconds.', beat: BEAT, beat0: TL.beat0, cuts: TL.shots.map(s => s.t), moments: TL.shots.map(s => s.moment), end: +(TL.start + TL.frames / TL.fps).toFixed(3), ...C };
fs.writeFileSync(path.join(HERE, 'cues.json'), JSON.stringify(out, null, 1));
console.log(Object.entries(C).map(([k, v]) => `${k} ${v}`).join('  '));
